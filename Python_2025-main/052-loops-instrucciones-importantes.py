'''
Instrucciones IMPORTANTES EN TODOS los loops

- break:
    - INTERRUMPE la iteración actual
    - INTERRUMPE el ciclo inmediatamente
    - SALE del ciclo

    Se utiliza cuando se ha alcanzado una condición que indica que no es
    necesario continuar con el ciclo

    
- continue:
    - INTERRUMPE la iteración actual
    - NO SALE del ciclo
    - SALTA el resto del código en esa iteración
    - CONTINUA con la siguiente iteración

    Se utiliza cuando hay una condición en la que no se quiere ejecutar 
    el código restante de la iteración actual, pero sí continuar con las
    siguientes iteraciones.


- pass
    - NO EJECUTA EL CODIGO en la iteración actual
    - NO EJECUTA NINGUNA OPERACION
    - NO SALE del ciclo
    - CONTINÚA con la ejecución del ciclo

    Se usa principalmente como un marcador de posición para que el código
    sea sintácticamente correcto, pero no afecta la ejecución.

    Es útil cuando se necesita una declaración que no haga nada por 
    razones de sintaxis.
'''

