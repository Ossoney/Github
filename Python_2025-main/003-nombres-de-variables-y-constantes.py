'''
Nombres de las variables

Regla 1: Legibilidad

    Hacer que el código se pueda leer con facilidad

    El nombre de la variable debe ser coherente con su contenido


Regla 2: Unidad

    El nombre de las variables debe estar compuesto por una sola unidad de texto.

    No puede estar separada por espacios en blanco

    En Python la práctica es usar letras minúsculas separadas por guiones bajos (snake_case)

    nombre_de_estudiante = 'Olga'


Regla 3: Alfabeto

    No usar caracteres con acentos, eñes o cualquier otro caracter ajeno al alfabeto inglés

    años => anios, anyos, anhos, annos



Regla 4: Números

    El nombre de las variables debe comenzar siempre con una letra

    mes_8 = 'agosto'

    
Regla 5: Signos:
    Las variables no pueden contener estos signos
        :       ?       #       -
        "       |       $       +
        '       \       %  
        ,       (       ^  
        <       )       &  
        >       !       *  
        /       @       ~  


Regla 6: Palabras clave
    No se pueden usar palabras clave del lenguaje como:

    input = "persona"
    print = ""Hola"
    string = "Python"
    int = 1500
    ...

    
Regla 7: Idioma
    Preferiblemente nombrar las variables en Inglés

    
Regla 8: Estilos

    b (una sola letra minúscula)

    B (una sola letra mayúscula) 

    minúsculas (lowecase)

    minúsculas_con_guiones_bajos

    MAYÚSCULAS (uppercase).

    MAYÚSCULAS_CON_GUIONES_BAJOS

    CapitalizedWords (o CapWords, o CamelCase StudlyCaps). 

        NOTA: Cuando use acrónimos en CapWords, escriba en mayúsculas todas las
        letras del acrónimo. Por lo tanto, HTTPServerError es mejor que 
        HttpServerError. 
    
    mixedCase (se diferencia de CapitalizedWords por el carácter inicial en 
    minúscula)
    
    Capitalized_Words_With_Underscore (esto es horrible!!!)

    
Regla 9: La regla 2W (Jorge Barrero y JC)
    Preferible y opcionalmente las variables del usuario deben nombrarse con 
    dos palabras (los lenguajes de programación no suelen usar variables 
    internas con esta característica)
'''

