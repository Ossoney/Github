'''
Una variable es un espacio de memoria (RAM) al que se le asigna un 
nombre y queda reservado para almacenar un valor.

Los valores en las variables  pueden variar durante el ciclo de vida del programa
'''

name_person = "Juan Carlos"
surname_person = "Varela Iglesias"

print(name_person + " " + surname_person)

name_person = 'José Carlos'
print(name_person + " " + surname_person)

'''
CONSTANTES:

Una constante es un valor que, por convención, no debe cambiar durante 
la ejecución del programa. 
'''

MY_CONSTANT = 77
print(MY_CONSTANT)

MY_CONSTANT = 'Esto es una supuesta constante'
print(MY_CONSTANT)

